"""Generate the human-readable ground-truth validation report.

Usage:
    python -m ground_truth.report            # from the backend dir
    python tests/ground_truth/report.py      # from the repo root

Writes a Markdown report to docs/VALIDATION.md and a machine-readable
report.json next to the corpus. The report is derived entirely from the
scan record, so a third party can reproduce it by re-running the harness.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.abspath(os.path.join(HERE, "..", ".."))
REPO = os.path.abspath(os.path.join(BACKEND, ".."))
for path in (BACKEND, os.path.join(BACKEND, "tests")):
    if path not in sys.path:
        sys.path.insert(0, path)

import services.scanner as scanner_mod  # noqa: E402
from ground_truth.harness import evaluate  # noqa: E402

if __package__ in (None, ""):
    # Running as a plain script path: make the package importable.
    sys.path.insert(0, os.path.join(BACKEND, "tests"))

PROFILE = "standard"


def _sim(target, profile=PROFILE, credential_checks=False):
    return scanner_mod.run_scan(target, profile=profile, simulate=True,
                                credential_checks=credential_checks)


def _table(rows, headers):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def render(result):
    pd = result["port_detection"]
    vf = result["vuln_flags"]
    cal = result["calibration"]
    rc = result["rank_calibration"]

    lines = []
    lines.append("# Ground-Truth Validation Report")
    lines.append("")
    lines.append("Generated by `backend/tests/ground_truth/report.py`. "
                 "Every number below is derived from the scan record, so it can "
                 "be reproduced by a third party by re-running the harness "
                 "against the same corpus.")
    lines.append("")
    lines.append(f"- Profile: `{result['profile']}`")
    lines.append(f"- Corpus: `backend/tests/ground_truth/corpus.json` "
                 f"({result['n_targets']} labeled reference targets)")
    lines.append(f"- Engine: `simulated` (deterministic per target)")
    lines.append("")

    lines.append("## 1. Port detection")
    lines.append("")
    lines.append(f"Open-port set compared against the labeled reference, "
                 f"target by target.")
    lines.append("")
    lines.append(_table([
        ["Precision", f"{pd['precision']:.4f}"],
        ["Recall", f"{pd['recall']:.4f}"],
        ["True positives", pd["true_positives"]],
        ["False positives", pd["false_positives"]],
        ["False negatives", pd["false_negatives"]],
    ], ["Metric", "Value"]))
    lines.append("")

    lines.append("## 2. Vulnerability flags")
    lines.append("")
    lines.append("Each flagged `http-vuln-*` script compared against the "
                 "reference flags for that target.")
    lines.append("")
    lines.append(_table([
        ["Precision", f"{vf['precision']:.4f}"],
        ["Recall", f"{vf['recall']:.4f}"],
        ["True positives", vf["true_positives"]],
        ["False positives", vf["false_positives"]],
        ["False negatives", vf["false_negatives"]],
    ], ["Metric", "Value"]))
    lines.append("")

    lines.append("## 3. Score calibration")
    lines.append("")
    lines.append("Each score checked against the band an analyst assigned to "
                 "that host, and against the corpus floor.")
    lines.append("")
    lines.append(_table([
        ["Targets in band", f"{cal['in_band']} / {result['n_targets']}"],
        ["Targets out of band", cal["out_of_band"]],
    ], ["Metric", "Value"]))
    lines.append("")

    lines.append("## 4. Rank calibration")
    lines.append("")
    lines.append("Spearman correlation between expert severity and risk "
                 "score. The correlation is negative by design: a more severe "
                 "host must score lower.")
    lines.append("")
    lines.append(f"- Spearman: **{rc['spearman']:.4f}**")
    lines.append(f"- Ordering inversions: **{rc['inversion_count']}**")
    lines.append("")
    if rc["inversions"]:
        lines.append(_table(
            [[i["more_severe"], i["more_severe_score"], i["less_severe"],
              i["less_severe_score"], i["gap"]] for i in rc["inversions"]],
            ["More severe host", "Score", "Less severe host", "Score", "Gap"]))
        lines.append("")
        lines.append("These inversions are a known limitation of the "
                     "count-based model: it deducts points per exposed port, "
                     "while an analyst weighs service criticality. A host with "
                     "many low-criticality ports can outscore one with fewer "
                     "but more dangerous services. The model is a rank, not a "
                     "measure of real exploitability.")
        lines.append("")

    lines.append("## 5. Expected vs. actual, per target")
    lines.append("")
    rows = []
    for d in result["disagreements"]:
        op = d["open_ports"]
        vf_ = d["vuln_flags"]
        rows.append([
            d["target"], d["expert_severity"], d["score"], d["grade"],
            d["grade_band"], "yes" if d["band_ok"] else "**no**",
            ", ".join(str(p) for p in op["expected"]) or "-",
            ", ".join(str(p) for p in op["actual"]) or "-",
            ", ".join(vf_["actual"]) or "-",
        ])
    lines.append(_table(rows, [
        "Target", "Expert severity", "Score", "Grade", "Expert band",
        "In band", "Expected ports", "Actual ports", "Vuln flags"]))
    lines.append("")

    lines.append("## 6. Scope and known limitations")
    lines.append("")
    lines.append("What this harness does and does not establish:")
    lines.append("")
    lines.append("- It validates the **scoring, compliance, and aggregation "
                 "path** end to end: that the engine reports what the "
                 "reference says, that the risk model lands where an analyst "
                 "would put it, and that the corpus expectations are met "
                 "exactly.")
    lines.append("- It runs against the **deterministic simulation engine**. "
                 "The simulation is seeded per target, so the corpus is a "
                 "stable, versioned oracle. It is not a substitute for "
                 "scanning a real host.")
    lines.append("- It does **not** validate the live nmap path. To do that, "
                 "point the corpus at real reference hosts and record the "
                 "expected ports by hand; the harness itself does not change.")
    lines.append("- The corpus was authored by hand from the simulation's "
                 "documented behaviour. That makes it a **regression guard**, "
                 "not an independent security oracle. An independent oracle "
                 "would be a second scanner (masscan, RustScan) or an external "
                 "index (Shodan, Censys) run against the same hosts.")
    lines.append("- A score is a **rank within a profile**, not a measure of "
                 "real exploitability. The inversions in section 4 are the "
                 "concrete evidence for that limit.")
    lines.append("")

    lines.append("## 7. Reproducing this report")
    lines.append("")
    lines.append("```")
    lines.append("cd backend")
    lines.append("python -m pytest tests/test_ground_truth.py -q")
    lines.append("python tests/ground_truth/report.py")
    lines.append("```")
    lines.append("")
    lines.append("The pytest suite regenerates `backend/tests/ground_truth/report.json` "
                 "and fails if the engine drifts from the corpus: a single "
                 "missed port, a spurious vulnerability flag, or a score that "
                 "leaves its expert band breaks the build.")
    lines.append("")
    return "\n".join(lines)


def main():
    result = evaluate(_sim, profile=PROFILE)
    with open(os.path.join(HERE, "report.json"), "w") as fh:
        json.dump(result, fh, indent=2)

    md = render(result)
    out_dir = os.path.join(REPO, "docs")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "VALIDATION.md")
    with open(out_path, "w") as fh:
        fh.write(md)
    print(f"Wrote {out_path}")
    print(f"Wrote {os.path.join(HERE, 'report.json')}")
    print(f"Port precision {result['port_detection']['precision']}, "
          f"recall {result['port_detection']['recall']}")
    print(f"Vuln precision {result['vuln_flags']['precision']}, "
          f"recall {result['vuln_flags']['recall']}")
    print(f"Calibration {result['calibration']['in_band']}"
          f"/{result['n_targets']} in band")
    print(f"Spearman {result['rank_calibration']['spearman']}")


if __name__ == "__main__":
    main()
